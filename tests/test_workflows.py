"""Static validation of every exported workflow (no n8n needed).

What this proves: the files are well-formed, wired together, free of embedded credentials and consistent with each other.
What it cannot prove: that the integrations work with real accounts. See "What was tested" in the README."""
import json
import re
from pathlib import Path

import pytest
from build_workflows import ERROR_WF_ID, IDS, build_all, render

ROOT = Path(__file__).resolve().parent.parent
FILES = sorted((ROOT / "workflows").rglob("*.json"))
PROD = [f for f in FILES if f.parent.name == "workflows" and not f.name.startswith("00-")]
DEMO = [f for f in FILES if f.parent.name == "demo"]
ERROR_FILE = ROOT / "workflows" / "00-error-handler.json"

# every node type the workflows use, with the typeVersions known to exist in n8n 1.123 (the pinned version)
KNOWN_TYPES = {
    "n8n-nodes-base.webhook": {2},
    "n8n-nodes-base.respondToWebhook": {1.4},
    "n8n-nodes-base.code": {2},
    "n8n-nodes-base.if": {2.3},
    "n8n-nodes-base.switch": {3.4},
    "n8n-nodes-base.httpRequest": {4.3},
    "n8n-nodes-base.gmailTrigger": {1.3},
    "n8n-nodes-base.gmail": {2.2},
    "n8n-nodes-base.googleSheets": {4.7},
    "n8n-nodes-base.slack": {2.4},
    "n8n-nodes-base.telegram": {1.2},
    "n8n-nodes-base.telegramTrigger": {1.2},
    "n8n-nodes-base.scheduleTrigger": {1.3},
    "n8n-nodes-base.errorTrigger": {1},
    "n8n-nodes-base.stopAndError": {1},
    "n8n-nodes-base.stickyNote": {1},
    "@n8n/n8n-nodes-langchain.chainLlm": {1.7},
    "@n8n/n8n-nodes-langchain.lmChatAnthropic": {1.3},
    "@n8n/n8n-nodes-langchain.outputParserStructured": {1.3},
}
TRIGGERS = {"n8n-nodes-base.webhook", "n8n-nodes-base.gmailTrigger", "n8n-nodes-base.telegramTrigger",
            "n8n-nodes-base.scheduleTrigger", "n8n-nodes-base.errorTrigger"}
SECRET_PATTERNS = [r"sk-ant-[A-Za-z0-9_-]{8,}", r"sk-[A-Za-z0-9]{20,}", r"xox[abprs]-[A-Za-z0-9-]{8,}", r"ghp_[A-Za-z0-9]{20,}",
                   r"AIza[0-9A-Za-z_-]{20,}", r"\b\d{8,10}:[A-Za-z0-9_-]{35}\b", r"-----BEGIN [A-Z ]*PRIVATE KEY", r"pat-[a-z]{2,3}\d?-[0-9a-f-]{20,}",
                   r"Bearer\s+[A-Za-z0-9._-]{20,}", r"eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\."]


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def real_nodes(wf: dict) -> list[dict]:
    return [n for n in wf["nodes"] if n["type"] != "n8n-nodes-base.stickyNote"]


def by_name(wf: dict) -> dict[str, dict]:
    return {n["name"]: n for n in wf["nodes"]}


def edges(wf: dict) -> list[tuple[str, str, str]]:
    return [(src, link["node"], kind) for src, kinds in wf["connections"].items() for kind, outs in kinds.items()
            for out in outs for link in out]


def test_the_expected_files_exist():
    assert len(PROD) == 3 and len(DEMO) == 3 and ERROR_FILE.exists()
    assert {f.name for f in FILES} == {"00-error-handler.json", "01-gmail-ai-triage.json", "02-support-chatbot-rag.json",
                                       "03-lead-intake-qualification.json", "01-gmail-ai-triage-demo.json",
                                       "02-support-chatbot-rag-demo.json", "03-lead-intake-qualification-demo.json"}


def test_committed_json_is_what_the_generator_produces():
    """The JSON is generated by scripts/build_workflows.py; hand edits would be lost, so fail loudly."""
    for rel, wf in build_all().items():
        assert (ROOT / "workflows" / rel).read_text(encoding="utf-8") == render(wf), f"{rel} is stale: run python scripts/build_workflows.py"


@pytest.mark.parametrize("path", FILES, ids=lambda p: p.name)
class TestEveryWorkflow:
    def test_parses_and_has_required_keys(self, path):
        wf = load(path)
        assert {"name", "nodes", "connections", "settings", "id"} <= wf.keys()
        assert wf["active"] is False  # activation is a deliberate step (import script / UI toggle)
        assert wf["nodes"] and isinstance(wf["connections"], dict)
        for n in wf["nodes"]:
            assert {"id", "name", "type", "typeVersion", "position", "parameters"} <= n.keys(), n.get("name")
            assert len(n["position"]) == 2

    def test_ids_and_names_are_unique_and_ids_are_stable(self, path):
        wf = load(path)
        assert len({n["id"] for n in wf["nodes"]}) == len(wf["nodes"])
        assert len({n["name"] for n in wf["nodes"]}) == len(wf["nodes"])
        assert re.fullmatch(r"[A-Za-z0-9]{16}", wf["id"]) and wf["id"] in IDS.values()

    def test_only_known_node_types_and_versions(self, path):
        for n in load(path)["nodes"]:
            assert n["type"] in KNOWN_TYPES, f"{n['name']}: unexpected type {n['type']}"
            assert n["typeVersion"] in KNOWN_TYPES[n["type"]], f"{n['name']}: typeVersion {n['typeVersion']}"

    def test_no_credentials_or_secrets_embedded(self, path):
        text = path.read_text(encoding="utf-8")
        wf = json.loads(text)
        assert all("credentials" not in n for n in wf["nodes"]), "node credentials must be created in n8n, not exported"
        for pattern in SECRET_PATTERNS:
            assert not re.search(pattern, text), f"looks like a secret: {pattern}"
        assert not re.search(r'"(password|apiKey|api_key|accessToken|access_token|secret|token)"\s*:\s*"[^"]', text, re.I)
        assert "pinData" not in text or wf["pinData"] == {}  # pinned data would be real payloads
        assert not re.search(r"https?://(?!127\.0\.0\.1|localhost|mail\.google\.com)[^\"\s]*\.(?:slack|hubspot|pipedrive)\.", text)

    def test_every_node_is_connected(self, path):
        wf = load(path)
        names = {n["name"] for n in real_nodes(wf)}
        es = edges(wf)
        for src, dst, _ in es:
            assert src in names and dst in names, f"dangling connection {src} -> {dst}"
        linked = {s for s, _, _ in es} | {d for _, d, _ in es}
        assert names - linked == set(), f"unconnected nodes: {names - linked}"
        incoming = {d for _, d, _ in es}
        for n in real_nodes(wf):
            if n["type"] in TRIGGERS:
                assert n["name"] not in incoming and n["name"] in {s for s, _, _ in es}, f"trigger {n['name']} must start a chain"
            elif not n["type"].endswith(("lmChatAnthropic", "outputParserStructured")):
                assert n["name"] in incoming, f"{n['name']} can never run (nothing leads to it)"

    def test_ai_nodes_are_wired_as_sub_nodes(self, path):
        wf = load(path)
        nodes = by_name(wf)
        for src, dst, kind in edges(wf):
            if nodes[src]["type"].endswith("lmChatAnthropic"):
                assert kind == "ai_languageModel" and nodes[dst]["type"].endswith("chainLlm")
            if nodes[src]["type"].endswith("outputParserStructured"):
                assert kind == "ai_outputParser" and nodes[dst]["type"].endswith("chainLlm")
        for n in wf["nodes"]:
            if n["type"].endswith("chainLlm"):
                kinds = {k for _, d, k in edges(wf) if d == n["name"]}
                assert "ai_languageModel" in kinds
                assert (n["parameters"].get("hasOutputParser") is True) == ("ai_outputParser" in kinds)
                system = n["parameters"]["messages"]["messageValues"][0]["message"]
                assert "{" not in system and "}" not in system, "curly braces in a chain system prompt are read as template variables"

    def test_every_http_node_retries(self, path):
        for n in load(path)["nodes"]:
            if n["type"] == "n8n-nodes-base.httpRequest":
                assert n.get("retryOnFail") is True and n.get("maxTries", 0) >= 2, f"{n['name']} has no retry settings"
                assert n["parameters"]["options"].get("timeout"), f"{n['name']} has no timeout"

    def test_code_nodes_have_code(self, path):
        for n in load(path)["nodes"]:
            if n["type"] == "n8n-nodes-base.code":
                assert n["parameters"]["mode"] in ("runOnceForAllItems", "runOnceForEachItem")
                assert "return" in n["parameters"]["jsCode"]

    def test_webhook_workflows_respond(self, path):
        wf = load(path)
        webhooks = [n for n in wf["nodes"] if n["type"] == "n8n-nodes-base.webhook"]
        if webhooks:
            assert all(w["parameters"]["responseMode"] == "responseNode" for w in webhooks)
            assert any(n["type"] == "n8n-nodes-base.respondToWebhook" for n in wf["nodes"])


@pytest.mark.parametrize("path", PROD + DEMO, ids=lambda p: p.name)
def test_error_workflow_is_set_and_exists(path):
    wf = load(path)
    assert wf["settings"]["errorWorkflow"] == ERROR_WF_ID
    err = load(ERROR_FILE)
    assert err["id"] == ERROR_WF_ID and any(n["type"] == "n8n-nodes-base.errorTrigger" for n in err["nodes"])
    assert "errorWorkflow" not in err["settings"]  # the handler must not point at itself


def test_error_workflow_can_alert_on_slack_telegram_or_the_demo_mock():
    err = load(ERROR_FILE)
    types = {n["type"] for n in err["nodes"]}
    assert {"n8n-nodes-base.slack", "n8n-nodes-base.telegram", "n8n-nodes-base.httpRequest"} <= types
    text = " ".join(n["parameters"].get("jsCode", "") for n in err["nodes"])
    for needle in ("wf.name", "lastNodeExecuted", "err.message", "ex.url"):
        assert needle in text  # workflow name, node, error and execution URL are all in the alert


