def test_configurable_endpoints_are_read_from_the_environment():
    support = json.dumps(load(ROOT / "workflows" / "02-support-chatbot-rag.json"))
    leads = json.dumps(load(ROOT / "workflows" / "03-lead-intake-qualification.json"))
    assert "$env.KB_SEARCH_URL" in support and "$env.CRM_BASE_URL" in leads
    crm = [n for n in load(ROOT / "workflows" / "03-lead-intake-qualification.json")["nodes"] if "CRM_BASE_URL" in n["parameters"].get("url", "")]
    assert len(crm) == 3 and all(n["parameters"]["authentication"] == "genericCredentialType" for n in crm)  # production CRM calls use a stored credential


def test_crm_failures_answer_the_caller_and_still_raise_the_alert():
    for f in (ROOT / "workflows" / "03-lead-intake-qualification.json", ROOT / "workflows" / "demo" / "03-lead-intake-qualification-demo.json"):
        wf = load(f)
        nodes = by_name(wf)
        for name in ("Find contact in CRM", "Update contact", "Create contact"):
            assert nodes[name]["onError"] == "continueErrorOutput"
            assert ("Tell caller: CRM unavailable") in {d for s, d, _ in edges(wf) if s == name}
        assert nodes["Tell caller: CRM unavailable"]["parameters"]["options"]["responseCode"] == 502
        assert nodes["Fail execution (raises the alert)"]["type"] == "n8n-nodes-base.stopAndError"
